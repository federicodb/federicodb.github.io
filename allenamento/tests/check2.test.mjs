import assert from 'node:assert/strict';
import { checkNumbers, checkExpr, polyCoeffs, factoredForm } from '../js/engine/check.js';
import { parse } from '../js/engine/expr.js';
assert.ok(checkNumbers('3; -2', { answers: [-2, 3] }).ok);
assert.ok(checkNumbers('x1 = 3 e x2 = -2', { answers: [-2, 3] }).ok);
assert.ok(checkNumbers('(2; 5)', { answers: [2, 5], ordered: true }).ok);
assert.equal(checkNumbers('(5; 2)', { answers: [2, 5], ordered: true }).ok, false);
assert.match(checkNumbers('(5; 2)', { answers: [2, 5], ordered: true }).message, /scambiato/);
assert.match(checkNumbers('3', { answers: [-2, 3] }).message, /manca/);
assert.ok(checkNumbers('0,5; 1/3', { answers: [1 / 3, 0.5] }).ok);
assert.ok(checkNumbers('4', { answers: [4] }).ok);
assert.deepEqual(polyCoeffs(parse('(x+1)(x-2)')), [-2, -1, 1]);
assert.deepEqual(polyCoeffs(parse('6x^2+9x')), [0, 9, 6]);
const ff = factoredForm();
assert.ok(checkExpr('3x(2x+3)', { answer: '6x^2+9x', form: ff }).ok);
assert.match(checkExpr('x(6x+9)', { answer: '6x^2+9x', form: ff }).message, /raccogliere/);
assert.match(checkExpr('6x^2+9x', { answer: '6x^2+9x', form: ff }).message, /prodotto/);
assert.ok(checkExpr('(x-3)(x+3)', { answer: 'x^2-9', form: ff }).ok);
assert.ok(checkExpr('(x+3)^2', { answer: 'x^2+6x+9', form: ff }).ok);
assert.match(checkExpr('(x^2-9)*1', { answer: 'x^2-9', form: ff }).message, /./);
assert.ok(checkExpr('(x-2)(x-3)', { answer: 'x^2-5x+6', form: ff }).ok);
assert.ok(checkExpr('-(x-2)(x+2)', { answer: '4-x^2', form: ff }).ok);
